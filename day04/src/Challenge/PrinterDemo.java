package Challenge; // 작성 중인 클래스가 속한 폴더(패키지) 이름입니다.

public class PrinterDemo {
    public static void main(String[] args) { // 자바 프로그램이 실행 시작되는 메인 메서드입니다.
        
        // 1. 용지 20장, 양면 인쇄 설정(true)으로 Printer 객체를 생성합니다.
        Printer p = new Printer(20, true);

        // 2. 양면 상태에서 25면을 출력하라고 명령합니다.
        //    - 양면 계산: (25 + 1) / 2 = 13장이 필요합니다.
        //    - 남은 용지(20장) >= 필요 용지(13장) 이므로 정상 출력됩니다.
        //    - 출력 후 남은 용지: 20 - 13 = 7장
        p.print(25);

        // 3. 양면 인쇄 설정을 꺼서 단면 인쇄 모드(false)로 변경합니다.
        p.setDuplex(false);

        // 4. 단면 상태에서 10장을 출력하라고 명령합니다.
        //    - 단면 계산: 10장이 필요합니다.
        //    - 남은 용지(7장) < 필요 용지(10장) 이므로 용지가 부족합니다.
        //    - 부족한 매수(3매)를 안내하고 남은 7장만 출력한 뒤, 용지는 0장이 됩니다.
        p.print(10);
    }
}