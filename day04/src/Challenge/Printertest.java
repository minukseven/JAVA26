package Challenge; // 작성 중인 클래스가 속한 폴더(패키지) 이름입니다.

public class Printertest {
    public static void main(String[] args) { // 자바 프로그램이 실행 시작되는 메인 메서드입니다.
        
        // 1. 처음 생성할 때 용지를 10장 가지고 있는 Printer 객체를 생성합니다.
        //    (duplex는 지정하지 않았으므로 기본값인 false, 즉 단면 인쇄 모드가 됩니다)
        Printer p = new Printer(10);

        // 2. 2장을 출력하라고 명령합니다.
        //    - 남은 용지(10장) >= 필요 용지(2장) 이므로 정상 출력됩니다.
        //    - 출력 후 남은 용지: 10 - 2 = 8장
        p.print(2);

        // 3. 20장을 출력하라고 명령합니다.
        //    - 남은 용지(8장) < 필요 용지(20장) 이므로 용지가 부족합니다.
        //    - 8장만 출력하고 부족한 매수(12매)를 안내한 뒤, 용지는 0장이 됩니다.
        p.print(20);

        // 4. 10장을 출력하라고 명령합니다.
        //    - 현재 남은 용지가 0장이므로 "용지가 없습니다." 메시지가 출력됩니다.
        p.print(10);
    }
}